"""Build responsive AVIF + WebP sets in public/img from originals in _raw/ and write lib/images.js.
Run: python3 scripts/optimize-images.py"""
import json, os
from PIL import Image, ImageOps

SRC, OUT = "_raw", "public/img"
os.makedirs(OUT, exist_ok=True)

# name: (file, max width, trim transparent margins)
MAP = {
    # Kemp's own assets (from kemps.in)
    "p-water-blue": ("products_2__kemps_water.png", 900, True),
    "p-water-pink": ("products_1__kemps_water_pink.png", 900, True),
    "p-eightplus": ("products_3__8+_plus.png", 900, True),
    "p-club-soda": ("products_club_soda.png", 900, True),
    "p-jeera-soda": ("products_jeera_soda.png", 900, True),
    "p-kokum": ("products_kokum_jeera_masala.png", 900, True),
    "p-lemon": ("products_lemon.png", 900, True),
    "p-mango": ("products_mango_200ml.png", 900, True),
    "p-orange": ("products_orange.png", 900, True),
    "p-pudina": ("products_pudina_twist.png", 900, True),
    "jeera-mockup": ("jeera_soda_bottle_mockup_copy.png", 1400, True),
    "ep-duo": ("EightPlusImages_123.png", 1500, True),
    "ep-splash": ("EightPlusImages_4.2.png", 1400, True),
    "ep-logo": ("EightPlusImages_8+_logo.png", 1000, True),
    "ep-banner": ("EightPlusImages_banner.jpg", 2400, False),
    "ph-glass": ("EightPlusImages_bottle.png", 1400, True),
    "award": ("aboutus_12x18in_photo_frame-bright__1_.jpg", 1800, False),
    # Ambient photography (generated for the site)
    "lake": ("lake.png", 2400, False),
    "river": ("river.png", 2400, False),
    "droplet": ("droplet.png", 2400, False),
}
STEPS = [400, 800, 1200, 1600, 2400]
meta = {}
for name, (src, maxw, trim) in MAP.items():
    im = Image.open(os.path.join(SRC, src))
    alpha = im.mode in ("RGBA", "LA", "P")
    im = im.convert("RGBA" if alpha else "RGB")
    if alpha and trim:
        bbox = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
        if bbox: im = im.crop(bbox)
    w, h = im.size
    top = min(w, maxw)
    widths = sorted(set([s for s in STEPS if s < top] + [top]))
    for tw in widths:
        r = im.resize((tw, round(h * tw / w)), Image.LANCZOS)
        r.save(f"{OUT}/{name}-{tw}.webp", "WEBP", quality=80, method=6)
        r.save(f"{OUT}/{name}-{tw}.avif", "AVIF", quality=60, speed=6)
    color = None if alpha else "#%02x%02x%02x" % im.convert("RGB").resize((1, 1)).getpixel((0, 0))
    meta[name] = {"w": w, "h": h, "widths": widths, "color": color}
    print(name, im.size, widths)

# Logos: knock the white background out of the blue JPG, then make a white version for dark backgrounds.
logo = Image.open(os.path.join(SRC, "Kemps_Final_Logo_BLUE.jpg")).convert("RGB")
px = logo.load()
out = Image.new("RGBA", logo.size)
op = out.load()
for y in range(logo.height):
    for x in range(logo.width):
        r, g, b = px[x, y]
        a = 255 - min(r, g, b)  # distance from white
        a = 0 if a < 18 else min(255, int(a * 1.25))
        if a:
            k = 255 / max(a, 1)
            op[x, y] = (max(0, min(255, int(255 - (255 - r) * k))), max(0, min(255, int(255 - (255 - g) * k))), max(0, min(255, int(255 - (255 - b) * k))), a)
out = out.crop(out.getchannel("A").getbbox())
out.thumbnail((900, 900), Image.LANCZOS)
out.save("public/logo-kemps.png", optimize=True)
white = Image.new("RGBA", out.size, (255, 255, 255, 0))
white.putalpha(out.getchannel("A"))
Image.composite(Image.new("RGBA", out.size, (255, 255, 255, 255)), white, out.getchannel("A")).save("public/logo-kemps-white.png", optimize=True)
meta["logo"] = {"w": out.width, "h": out.height}

# WebGL label + environment
lab = out.copy(); lab.thumbnail((700, 700)); lab.save(f"{OUT}/label-logo.png")
Image.open(os.path.join(SRC, "lake.png")).convert("RGB").resize((1280, 714), Image.LANCZOS).save(f"{OUT}/lake-1280.webp", "WEBP", quality=72)
# Open Graph
og = Image.open(os.path.join(SRC, "EightPlusImages_banner.jpg")).convert("RGB")
og = ImageOps.fit(og, (1200, 630), Image.LANCZOS)
og.save("public/og.jpg", "JPEG", quality=82)
with open("lib/images.js", "w") as f:
    f.write("// Generated by scripts/optimize-images.py — do not edit by hand.\nexport const IMAGES = " + json.dumps(meta, indent=1) + ";\n")
