"""Convert source PNGs in _raw/ into responsive AVIF + WebP sets in public/img and write lib/images.js."""
import json, os, sys
from PIL import Image

SRC = "_raw"
OUT = "public/img"
# name -> (source file, crop aspect w/h or None)
MAP = {
    "lake": ("lake.png", None), "river": ("river.png", None), "droplet": ("droplet.png", None),
    "facility": ("facility.png", None), "ice": ("ice.png", None), "splash": ("splash.png", None),
    "lineup": ("lineup.png", None), "dining": ("dining.png", None), "fitness": ("fitness.png", None),
    "travel": ("travel.png", None), "work": ("work.png", None), "hotel": ("hotel.png", None),
    "case": ("case.png", None), "sustain": ("sustain.png", None), "studio": ("studio.png", None),
    "bottle-330": ("bottle330.png", None), "bottle-500": ("studio.png", None), "bottle-1000": ("bottle1000.png", None),
}
WIDTHS = [480, 960, 1440, 1920]
os.makedirs(OUT, exist_ok=True)
meta = {}
for name, (src, _) in MAP.items():
    im = Image.open(os.path.join(SRC, src)).convert("RGB")
    w, h = im.size
    widths = [x for x in WIDTHS if x < w] + [min(w, 2400)]
    widths = sorted(set(x for x in widths if x <= 2400))
    if name in ("bottle-330", "bottle-500", "bottle-1000", "studio"):
        widths = [x for x in widths if x <= 1440] or widths[:1]
    for tw in widths:
        th = round(h * tw / w)
        r = im.resize((tw, th), Image.LANCZOS)
        r.save(f"{OUT}/{name}-{tw}.webp", "WEBP", quality=78, method=6)
        r.save(f"{OUT}/{name}-{tw}.avif", "AVIF", quality=58, speed=6)
    # average colour as placeholder background
    c = im.resize((1, 1), Image.LANCZOS).getpixel((0, 0))
    meta[name] = {"w": w, "h": h, "widths": widths, "color": "#%02x%02x%02x" % c}
    print(name, widths)
# environment map for WebGL
im = Image.open(os.path.join(SRC, "lake.png")).convert("RGB").resize((1280, 714), Image.LANCZOS)
im.save(f"{OUT}/lake-1280.webp", "WEBP", quality=72)
# OG image
og = Image.open(os.path.join(SRC, "splash.png")).convert("RGB").resize((1200, 670), Image.LANCZOS).crop((0, 0, 1200, 630))
og.save("public/og.jpg", "JPEG", quality=82)
with open("lib/images.js", "w") as f:
    f.write("// Generated by scripts/optimize-images.py — do not edit by hand.\nexport const IMAGES = " + json.dumps(meta, indent=1) + ";\n")
